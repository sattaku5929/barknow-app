-- Derive local_date from the timestamp and validated timezone on every write.
-- The owner/dog assertion prevents inconsistent ownership even for privileged writes.
create or replace function public.wt_prepare_observation_entry()
returns trigger
language plpgsql
set search_path = public, pg_catalog
as $$
begin
  if not exists (
    select 1 from pg_catalog.pg_timezone_names where name = new.timezone
  ) then
    raise exception 'unsupported observation timezone: %', new.timezone
      using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.wt_dogs dog
    where dog.id = new.dog_id and dog.owner_id = new.owner_id
  ) then
    raise exception 'observation owner does not own the selected dog'
      using errcode = '23514';
  end if;

  if tg_op = 'UPDATE' then
    if new.owner_id <> old.owner_id
       or new.dog_id <> old.dog_id
       or new.entry_kind <> old.entry_kind
       or new.source <> old.source then
      raise exception 'observation owner, dog, kind, and source are immutable'
        using errcode = '23514';
    end if;
    new.created_at := old.created_at;
  end if;

  new.local_date := (new.occurred_at at time zone new.timezone)::date;
  new.updated_at := now();
  return new;
end;
$$;

revoke all on function public.wt_prepare_observation_entry() from public, anon, authenticated;

create trigger wt_prepare_observation_entry_before_write
  before insert or update on public.wt_observation_entries
  for each row execute function public.wt_prepare_observation_entry();

