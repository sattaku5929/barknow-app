create table public.wt_dog_observation_themes (
  id uuid primary key default gen_random_uuid(),
  dog_id uuid not null references public.wt_dogs(id) on delete cascade,
  theme_key text not null check (
    theme_key in (
      'barking',
      'walk',
      'alone',
      'toilet',
      'dog_reaction',
      'person_reaction',
      'biting',
      'meal',
      'sleep_rest',
      'grooming'
    )
  ),
  sort_order smallint not null check (sort_order between 1 and 3),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dog_id, theme_key),
  unique (dog_id, sort_order)
);

comment on table public.wt_dog_observation_themes is
  'Up to three canonical observation themes selected for each dog.';
comment on column public.wt_dog_observation_themes.sort_order is
  'Positions 1-3 also enforce the per-dog maximum without a race-prone count trigger.';

create table public.wt_observation_entries (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  dog_id uuid not null references public.wt_dogs(id) on delete cascade,
  entry_kind text not null check (entry_kind in ('daily_check', 'event')),
  theme_key text,
  occurred_at timestamptz not null,
  timezone text not null default 'Asia/Tokyo' check (char_length(timezone) between 1 and 100),
  local_date date not null,
  note text check (note is null or char_length(note) <= 5000),
  schema_version integer not null default 1 check (schema_version > 0),
  source text not null default 'owner' check (source in ('owner', 'coach', 'import')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint wt_observation_entries_theme_check check (
    (entry_kind = 'daily_check' and theme_key is null)
    or
    (
      entry_kind = 'event'
      and theme_key in (
        'barking',
        'walk',
        'alone',
        'toilet',
        'dog_reaction',
        'person_reaction',
        'biting',
        'meal',
        'sleep_rest',
        'grooming'
      )
    )
  ),
  constraint wt_observation_entries_deleted_at_check check (
    deleted_at is null or deleted_at >= created_at
  )
);

