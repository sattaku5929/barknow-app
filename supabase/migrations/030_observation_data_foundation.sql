-- Enforce the one-to-one subtype and parent entry_kind relationship.
create or replace function public.wt_validate_observation_subtype()
returns trigger
language plpgsql
set search_path = public, pg_catalog
as $$
declare
  expected_kind text := tg_argv[0];
begin
  if not exists (
    select 1 from public.wt_observation_entries entry
    where entry.id = new.entry_id and entry.entry_kind = expected_kind
  ) then
    raise exception 'observation subtype requires entry_kind %', expected_kind
      using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke all on function public.wt_validate_observation_subtype() from public, anon, authenticated;

create trigger wt_validate_daily_check_before_write
  before insert or update on public.wt_daily_checks
  for each row execute function public.wt_validate_observation_subtype('daily_check');

create trigger wt_validate_observation_event_before_write
  before insert or update on public.wt_observation_events
  for each row execute function public.wt_validate_observation_subtype('event');

